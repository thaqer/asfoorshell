#include "libft.h"

int	ft_memcmp(const void *s1, const void *s2, size_t n)
{
	unsigned char	*ptr1;
	unsigned char	*ptr2;
	size_t			x;

	x = 0;
	ptr1 = (unsigned char *)s1;
	ptr2 = (unsigned char *)s2;
	while (x < n)
	{
		if (ptr1[x] != ptr2[x])
			return (ptr1[x] - ptr2[x]);
		x++;
	}
	return (0);
}
