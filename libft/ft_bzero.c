#include "libft.h"

void	ft_bzero(void *s, size_t n)
{
	unsigned char	*ptr;
	size_t			x;

	ptr = (unsigned char *)s;
	x = 0;
	while (x < n)
	{
		ptr[x] = '\0';
		x++;
	}
}
