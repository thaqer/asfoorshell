#include "libft.h"

void	*ft_memset(void *s, int c, size_t n)
{
	size_t			x;
	unsigned char	*ptr;
	unsigned char	value;

	ptr = (unsigned char *)s;
	value = (unsigned char)c;
	x = 0;
	while (x < n)
	{
		ptr[x] = value;
		x++;
	}
	return (s);
}
