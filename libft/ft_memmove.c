#include "libft.h"

void	*ft_memmove(void *dest, const void *src, size_t n)
{
	unsigned char	*s;
	unsigned char	*d;
	size_t			x;

	s = (unsigned char *)src;
	d = (unsigned char *)dest;
	x = 0;
	if (!dest && !src)
		return (NULL);
	if (d > s)
	{
		while (n-- > 0)
		{
			d[n] = s[n];
		}
	}
	else
	{
		while (x < n)
		{
			d[x] = s[x];
			x++;
		}
	}
	return (dest);
}
